create or replace function public.admin_set_profile_access(
  target_user_id uuid,
  new_role public.app_role,
  new_is_active boolean
)
returns public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
  changed_profile public.profiles;
  previous public.profiles;
begin
  if not public.is_admin() then
    raise exception 'administrator privileges required'
      using errcode = '42501';
  end if;

  select * into previous from public.profiles where id = target_user_id;
  if previous.id is null then
    raise exception 'profile not found'
      using errcode = 'P0002';
  end if;

  update public.profiles
  set role = new_role,
      is_active = new_is_active
  where id = target_user_id
  returning * into changed_profile;

  insert into public.profile_role_audit (
    target_user_id, actor_id, previous_role, new_role,
    previous_is_active, new_is_active, reason
  ) values (
    target_user_id,
    auth.uid(),
    previous.role,
    new_role,
    previous.is_active,
    new_is_active,
    'admin_set_profile_access'
  );

  return changed_profile;
end;
$$;

