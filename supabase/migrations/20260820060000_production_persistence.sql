create or replace function public.revoke_manufacturing_quote(
  target_quote_id uuid,
  revoke_reason text,
  actor_user_id uuid default null
)
returns public.quote_revocations
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_id uuid;
  actor_role public.app_role;
  record public.quote_revocations;
begin
  actor_id := coalesce(auth.uid(), actor_user_id);
  if actor_id is null then
    raise exception 'actor required'
      using errcode = '42501';
  end if;

  select role into actor_role
  from public.profiles
  where id = actor_id and is_active;

  if actor_role is distinct from 'owner'::public.app_role then
    raise exception 'owner privileges required'
      using errcode = '42501';
  end if;

  if auth.uid() is not null and auth.uid() is distinct from actor_id then
    raise exception 'actor mismatch'
      using errcode = '42501';
  end if;

  if not exists (
    select 1 from public.manufacturing_quotes where id = target_quote_id
  ) then
    raise exception 'quote not found'
      using errcode = 'P0002';
  end if;

  if exists (
    select 1 from public.quote_revocations where quote_id = target_quote_id
  ) then
    raise exception 'quote already revoked'
      using errcode = '23505';
  end if;

  if public.quote_has_linked_order(target_quote_id) then
    raise exception 'order-linked quotes cannot be revoked'
      using errcode = '23514';
  end if;

  insert into public.quote_revocations (quote_id, reason, revoked_by)
  values (target_quote_id, btrim(revoke_reason), actor_id)
  returning * into record;

  return record;
end;
$$;

revoke all on function public.revoke_manufacturing_quote(uuid, text, uuid) from public;
grant execute on function public.revoke_manufacturing_quote(uuid, text, uuid)
  to authenticated, service_role;

